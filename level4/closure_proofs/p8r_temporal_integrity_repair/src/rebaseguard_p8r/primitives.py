"""Addressable primitive exogenous random field (P6R2b standard, inherited).

The repaired Priority-6 standard (``p6r2b_gate9_crn_identity``) is adopted
verbatim in its *property*: every raw draw is a **pure function of its
address**, and the address contains no live-set position, no execution order,
no stopping time, no branch order, no count of previously consumed draws, and
none of the quantities a comparison varies.  The P8 adjudication confirmed this
layer as ``P8_CRN_IDENTITY = PASS`` and ``WINDOW_EXTRACTION = EXACT``; P8R
inherits the implementation unchanged **except** for one addition:

    the ``experiment`` component must be a tag minted by
    :func:`addressing.tag`, so every address carries its
    :class:`~addressing.AddressClass` and the four classes are disjoint by
    construction.

P8R addresses
-------------
Stopped-cycle field (``stopped.py``, ``calibrate.py``)::

    (SEED_NAMESPACE, tag_digest(experiment), family, batch, row_block, block)

Deliberately **absent**: the detector, the window ``m``, the window convention,
the lag depth.  Those are exactly the axes P8R compares, so excluding them makes
every detector / window / convention comparison a common-random-number
comparison on identical innovation paths.

Chain field (``chain.py``)::

    (SEED_NAMESPACE, tag_digest(experiment), family, detector, m, cycle,
     primitive_type, block_index)

Deliberately **absent**: ``rho``, the shift size, the drift pattern and the
replicate's history.  Those are the axes the chain experiments compare.

Blocks
------
Values are materialised in blocks of ``BLOCK_LEN`` observations for a fixed band
of ``ROWS_PER_BLOCK`` replicates, generated by a counter-based **Philox** stream
keyed only on the address.  Block ``b`` is generated independently of whether
block ``b-1`` was ever generated, so **overflow past the end of any
pre-generated tape is not a special case**: observation ``t`` lives at block
``t // BLOCK_LEN``, offset ``t % BLOCK_LEN``, row ``p % ROWS_PER_BLOCK`` of row
block ``p // ROWS_PER_BLOCK``, for every ``t``, forever.

``BLOCK_LEN`` is deliberately small so that overflow is routine in the ordinary
experiment (the operating ARL is ~465, i.e. ~4 blocks per cycle) rather than
reachable only by a contrived test.
"""
from __future__ import annotations

import hashlib

import numpy as np

from . import families as _families
from .addressing import tag_digest
from .config import SEED_NAMESPACE

BLOCK_LEN = 128
ROWS_PER_BLOCK = 4096

MONITOR = "monitor"      # raw observations feeding the detector
FRESH = "fresh"          # post-alarm fresh baseline observations
INIT = "init"            # initialisation randomness
AUX = "aux"              # auxiliary simulator randomness
PRIMITIVE_TYPES = (MONITOR, FRESH, INIT, AUX)


def _tag(s: str) -> int:
    return int.from_bytes(hashlib.sha256(s.encode()).digest()[:8], "big")


def stopped_address(experiment: str, family: str, batch: int, row_block: int,
                    block_index: int) -> tuple:
    """The full stopped-field address.  ``experiment`` must be a minted tag."""
    if min(int(batch), int(row_block), int(block_index)) < 0:
        raise ValueError("address components must be non-negative")
    return (SEED_NAMESPACE, tag_digest(experiment), _tag(family), int(batch),
            int(row_block), int(block_index))


def chain_address(experiment: str, family: str, detector: str, m: int,
                  cycle: int, primitive_type: str, block_index: int) -> tuple:
    if primitive_type not in PRIMITIVE_TYPES:
        raise ValueError(f"unknown primitive type {primitive_type!r}")
    if min(int(m), int(cycle), int(block_index)) < 0:
        raise ValueError("address components must be non-negative")
    return (SEED_NAMESPACE, tag_digest(experiment), _tag(family),
            _tag(detector), int(m), int(cycle), _tag(primitive_type),
            int(block_index))


# The block caches are keyed on the full address, so a cache hit can only ever
# return the value that address defines.  ``maxsize`` therefore affects speed
# and nothing else; ``tests/test_crn_identity.py`` asserts that directly by
# clearing the cache mid-comparison.
_STOPPED_CACHE: dict = {}
_STOPPED_CACHE_MAX = 8
_CHAIN_CACHE: dict = {}
_CHAIN_CACHE_MAX = 64


def _evict(cache: dict, cap: int) -> None:
    while len(cache) > cap:
        cache.pop(next(iter(cache)))


def _stopped_block(experiment: str, family: str, batch: int, row_block: int,
                   block_index: int, n_rows: int, width: int) -> np.ndarray:
    key = (experiment, family, batch, row_block, block_index, n_rows, width)
    hit = _STOPPED_CACHE.get(key)
    if hit is not None:
        return hit
    ss = np.random.SeedSequence(
        list(stopped_address(experiment, family, batch, row_block, block_index)))
    rng = np.random.Generator(np.random.Philox(ss))
    a = _families.get(family).draw(rng, (int(n_rows), int(width)))
    a = np.ascontiguousarray(a, dtype=float)
    a.flags.writeable = False
    _STOPPED_CACHE[key] = a
    _evict(_STOPPED_CACHE, _STOPPED_CACHE_MAX)
    return a


def stopped_block(experiment: str, family: str, batch: int, row_block: int,
                  block_index: int, n_rows: int = ROWS_PER_BLOCK,
                  width: int = BLOCK_LEN) -> np.ndarray:
    """``(n_rows, width)`` block of innovations at one address.  Read-only."""
    return _stopped_block(experiment, family, int(batch), int(row_block),
                          int(block_index), int(n_rows), int(width))


def stopped_column(experiment: str, family: str, batch: int, index: int,
                   n_paths: int) -> np.ndarray:
    """All ``n_paths`` paths' innovation at observation ``index``.

    Order-independent and live-set-independent: the value returned for path
    ``p`` depends only on ``(experiment, family, batch, p, index)``.
    """
    b, off = divmod(int(index), BLOCK_LEN)
    n_rb = -(-int(n_paths) // ROWS_PER_BLOCK)
    out = np.empty(int(n_paths))
    for rb in range(n_rb):
        lo = rb * ROWS_PER_BLOCK
        hi = min(lo + ROWS_PER_BLOCK, int(n_paths))
        out[lo:hi] = stopped_block(experiment, family, batch, rb, b)[:hi - lo, off]
    return out


def stopped_value(experiment: str, family: str, batch: int, path: int,
                  index: int) -> float:
    """One innovation, by address.  Works for ANY ``index`` and any ``path``."""
    b, off = divmod(int(index), BLOCK_LEN)
    rb, row = divmod(int(path), ROWS_PER_BLOCK)
    return float(stopped_block(experiment, family, batch, rb, b)[row, off])


#: replicates per addressable row band of the chain field.  Row banding is an
#: efficiency device only: the value delivered to replicate ``r`` depends on
#: ``r // CHAIN_ROWS`` and ``r % CHAIN_ROWS``, both fixed a priori, so which
#: bands a run happens to *materialise* cannot change any delivered value.
CHAIN_ROWS = 256


def _chain_block(experiment: str, family: str, detector: str, m: int,
                 cycle: int, primitive_type: str, block_index: int,
                 row_band: int, n_rows: int, width: int) -> np.ndarray:
    key = (experiment, family, detector, m, cycle, primitive_type, block_index,
           row_band, n_rows, width)
    hit = _CHAIN_CACHE.get(key)
    if hit is not None:
        return hit
    ss = np.random.SeedSequence(
        list(chain_address(experiment, family, detector, m, cycle,
                           primitive_type, block_index)) + [int(row_band)])
    rng = np.random.Generator(np.random.Philox(ss))
    a = _families.get(family).draw(rng, (int(n_rows), int(width)))
    a = np.ascontiguousarray(a, dtype=float)
    a.flags.writeable = False
    _CHAIN_CACHE[key] = a
    _evict(_CHAIN_CACHE, _CHAIN_CACHE_MAX)
    return a


def chain_block(experiment: str, family: str, detector: str, m: int, cycle: int,
                primitive_type: str, block_index: int, n_rep: int,
                width: int = BLOCK_LEN, row_band: int = 0,
                n_rows: int | None = None) -> np.ndarray:
    if n_rows is None:
        n_rows = min(CHAIN_ROWS, int(n_rep) - int(row_band) * CHAIN_ROWS)
    return _chain_block(experiment, family, detector, int(m), int(cycle),
                        primitive_type, int(block_index), int(row_band),
                        int(n_rows), int(width))


def _n_bands(n_rep: int) -> int:
    return -(-int(n_rep) // CHAIN_ROWS)


def chain_monitor_column(experiment: str, family: str, detector: str, m: int,
                         cycle: int, index: int, n_rep: int,
                         need: np.ndarray | None = None) -> np.ndarray:
    """All replicates' monitor observation at one index.  Order-independent.

    ``need`` is an optional boolean mask of replicates whose value will actually
    be read; row bands containing no needed replicate are not materialised and
    their entries come back as ``nan``.  This is purely an efficiency device --
    the value delivered to any replicate is unchanged by it, which
    ``tests/test_crn_identity.py`` asserts directly.
    """
    b, off = divmod(int(index), BLOCK_LEN)
    out = np.full(int(n_rep), np.nan)
    for band in range(_n_bands(n_rep)):
        lo = band * CHAIN_ROWS
        hi = min(lo + CHAIN_ROWS, int(n_rep))
        if need is not None and not need[lo:hi].any():
            continue
        out[lo:hi] = chain_block(experiment, family, detector, m, cycle,
                                 MONITOR, b, n_rep, row_band=band)[:hi - lo, off]
    return out


def chain_fresh(experiment: str, family: str, detector: str, m: int, cycle: int,
                n_rep: int) -> np.ndarray:
    """All replicates' fresh reference statistic for one cycle.

    Frozen convention: ``mu_fresh = (1/m) sum_{r<m} Y_r`` with ``Y_r`` iid from
    the family, independent of the stopping event.  For a non-Gaussian family
    this is **not** distributed as ``eps / sqrt(m)``, so the ``m`` draws are
    taken explicitly rather than a single scaled draw.
    """
    parts = []
    for band in range(_n_bands(n_rep)):
        parts.append(chain_block(experiment, family, detector, m, cycle, FRESH,
                                 0, n_rep, width=max(int(m), 1), row_band=band))
    return np.concatenate(parts, axis=0)[:int(n_rep), :int(m)].mean(axis=1)


def chain_init(experiment: str, family: str, detector: str, m: int,
               n_rep: int, width: int) -> np.ndarray:
    """Initialisation primitives (finite-reference regime).  Addressable even
    when the experiment ignores them."""
    parts = [chain_block(experiment, family, detector, m, 0, INIT, 0, n_rep,
                         width=max(int(width), 1), row_band=band)
             for band in range(_n_bands(n_rep))]
    return np.concatenate(parts, axis=0)[:int(n_rep)]


DIGEST_OFFSETS = (0, 1, 63, 127)


def chain_field_digest(experiment: str, family: str, detector: str, m: int,
                       n_rep: int, n_cycles: int, max_block_index: int,
                       offsets=DIGEST_OFFSETS) -> str:
    """SHA-256 digest of the chain primitive field over the touched addresses.

    Exhaustive over ``(cycle, block_index)`` for every cycle and every block any
    variant reached and over all replicates and all fresh draws; sampled at the
    declared offsets within each monitor block.  Computed from the address
    alone: it takes no ``rho``, no shift and no live-set argument, so it cannot
    depend on which variant asks.
    """
    h = hashlib.sha256()
    h.update(f"ns={SEED_NAMESPACE} exp={experiment} fam={family} det={detector} "
             f"m={m} n_rep={n_rep} n_cycles={n_cycles} blk={BLOCK_LEN} "
             f"off={tuple(offsets)}".encode())
    for j in range(int(n_cycles)):
        h.update(np.ascontiguousarray(
            chain_fresh(experiment, family, detector, m, j, n_rep)).tobytes())
        for b in range(int(max_block_index) + 1):
            col_band = [chain_block(experiment, family, detector, m, j,
                                    MONITOR, b, n_rep, row_band=band)
                        for band in range(_n_bands(n_rep))]
            blk = np.concatenate(col_band, axis=0)[:int(n_rep)]
            for off in offsets:
                h.update(np.ascontiguousarray(blk[:, off]).tobytes())
    return h.hexdigest()


def clear_cache() -> None:
    _STOPPED_CACHE.clear()
    _CHAIN_CACHE.clear()
