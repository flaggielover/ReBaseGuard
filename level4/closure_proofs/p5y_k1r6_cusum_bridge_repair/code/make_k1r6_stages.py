def sha_bytes(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def pins() -> dict:
    aux = json.loads((AUX4 / "manifests/producer_manifest_v2.json").read_text())["files"]
    out = {}
    for k, p in SOURCES.items():
        if k == "k1r5_entry":
            want = json.loads((K1R5 / "config/CHECKPOINT.json").read_text())["wrapper_sha256"]
            pin = "p5y_k1r5_cusum_entry/config/CHECKPOINT.json wrapper_sha256"
        else:
            rel = str(p.relative_to(REPO))
            want, pin = aux[rel], f"aux4 producer_manifest_v2 files[{rel}]"
        got = sha_bytes(p.read_bytes())
        if got != want:
            raise SystemExit(f"FROZEN_SOURCE_DRIFT: {p} sha256 {got} != pinned {want} ({pin})")
        out[k] = {"path": str(p), "sha256": got, "pinned_by": pin}
    return out


def sub(text: str, s: tuple) -> str:
    old, new, cat, n, note = s
    assert cat in CATEGORIES, cat
    got = text.count(old)
    if got != n:
        raise SystemExit(f"SUBSTITUTION_COUNT: {cat} expected {n} occurrence(s), found {got}: {old[:70]!r}")
    return text.replace(old, new)


def header(src_key: str, sha: str) -> str:
    return (f"# GENERATED by code/make_k1r6_stages.py from {SOURCES[src_key].name} (sha256 {sha}).\n"
            "# Frozen text with exactly the counted substitutions (and declared additions) recorded in\n"
            "# config/TRANSFORMATION_MANIFEST.json. Do not edit by hand.\n")


def rec(s: tuple) -> dict:
    old, new, cat, n, note = s
    return {"category": cat, "old": old, "new": new, "expected_occurrences": n, "note": note}


