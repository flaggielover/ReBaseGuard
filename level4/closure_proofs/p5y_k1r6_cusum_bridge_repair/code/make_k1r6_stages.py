def main(argv=None) -> int:
    check = "--check" in (argv if argv is not None else sys.argv[1:])
    files, man = generate()
    mbytes = (json.dumps(man, indent=1, sort_keys=True) + "\n").encode()
    if check:
        bad = [n for n, b in files.items() if (OUT / n).read_bytes() != b.encode()]
        if (NS / "config/TRANSFORMATION_MANIFEST.json").read_bytes() != mbytes:
            bad.append("TRANSFORMATION_MANIFEST.json")
        print(json.dumps({"regenerated_equal_on_disk": not bad, "differs": bad}))
        return 0 if not bad else 1
    OUT.mkdir(exist_ok=True)
    for n, b in files.items():
        (OUT / n).write_text(b)
    (NS / "config/TRANSFORMATION_MANIFEST.json").write_bytes(mbytes)
    print(json.dumps({n: v["generated_sha256"] for n, v in man["stages"].items()}, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
