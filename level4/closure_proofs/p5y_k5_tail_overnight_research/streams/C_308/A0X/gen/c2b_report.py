"""C2b aggregator: gen/results/*.json -> NS/validation/C2B_VALIDATION.json + markdown tables (stdout).

Every number in the tables is regenerated from the result files, which are regenerated by c2b_validate.py /
c2b_controls.py.  Tightness = (certified - truth)/truth with truth = NON-CERTIFIED Nystrom-Richardson (finest pair).
"""
from __future__ import annotations

import json
from fractions import Fraction as F

import c2b_common as CM

RES = CM.HERE / "results"


def _load(pattern):
    return {p.stem: json.loads(p.read_text()) for p in sorted(RES.glob(pattern))}


def truth_table():
    T = {}
    for name, t in _load("truth_*.json").items():
        e = t["e"]
        d = T.setdefault(e, {"meshes": {}})
        for m in t["meshes"]:
            d["meshes"][m["N"]] = m
    for e, d in T.items():
        Ns = sorted(d["meshes"])
        best = {}
        for key in ("Lambda", "tau_a", "C_T"):
            vals = [d["meshes"][n][key] for n in Ns]
            rich = [((Ns[r + 1] / Ns[r]) ** 2 * vals[r + 1] - vals[r]) / ((Ns[r + 1] / Ns[r]) ** 2 - 1)
                    for r in range(len(Ns) - 1)]
            best[key] = {"meshes": dict(zip(Ns, vals)), "richardson": rich,
                         "best": rich[-1] if rich else vals[-1],
                         "uncertainty": abs(rich[-1] - rich[-2]) if len(rich) > 1 else
                         (abs(vals[-1] - vals[-2]) if len(vals) > 1 else None)}
        d["best"] = best
    return T


def point_rows(T):
    rows = []
    for name, r in _load("point_*.json").items():
        c = r["certificate"]
        e = r["e_lo"]
        kind = r["kind"]
        if c is None:      # selection found no feasible (alpha, beta) on the declared grid: NOT CERTIFIED
            rows.append({"e": e, "N": r["N"], "kind": kind, "family": r["family"], "certified": False,
                         "note": "no feasible parameters on the declared selection grid",
                         "cpu_s": r["cpu_seconds"]["total"]})
            continue
        tb = T.get(e, {}).get("best", {})
        row = {"e": e, "N": r["N"], "kind": kind, "family": r["family"], "certified": c["certified"],
               "alpha": r["alpha_float"], "beta": r["beta_float"], "bumps": r["bumps"],
               "cpu_s": r["cpu_seconds"]["total"], "cells": c.get("cells_checked")}
        if kind == "whole":
            row["bound"] = c["w_atom_float"]
            row["bound_exact"] = c["w_atom"]
            tr = tb.get("Lambda")
            row["truth"] = tr["best"] if tr else None
            row["truth_unc"] = tr["uncertainty"] if tr else None
            row["tightness_pct"] = 100 * (row["bound"] / row["truth"] - 1) if tr else None
        else:
            row["bound"] = c["w_atom_float"]
            row["bound_exact"] = c["w_atom"]
            row["C_T_bound"] = float(F(c["w_max"]))
            tr, tc = tb.get("tau_a"), tb.get("C_T")
            row["truth"] = tr["best"] if tr else None
            row["truth_unc"] = tr["uncertainty"] if tr else None
            row["tightness_pct"] = 100 * (row["bound"] / row["truth"] - 1) if tr else None
            row["C_T_truth"] = tc["best"] if tc else None
            row["C_T_tightness_pct"] = 100 * (row["C_T_bound"] / row["C_T_truth"] - 1) if tc else None
        rows.append(row)
    rows.sort(key=lambda x: (F(x["e"]), x["kind"], x["family"], x["N"]))
    for x in rows:
        if x["family"] == "F0_affine_m" and x.get("alpha") is not None and x["alpha"] >= 8.0:
            x["note"] = "slope at the upper edge of the declared F0 grid (k/256, k < 2^11): value is grid-limited"
    return rows


def block_rows(T=None):
    grids = _load("truthgrid_*.json")
    rows = []
    for name, r in _load("block_*.json").items():
        c = r["certificate"]
        e_lo, e_hi = F(r["e_lo"]), F(r["e_hi"])
        sup = None
        mono = None
        for g in grids.values():
            pts = [(F(p["e"]), p["Lambda_richardson"]) for p in g["points"] if e_lo <= F(p["e"]) <= e_hi]
            if pts and F(g["e0"]) == e_lo:
                sup = max(v for _, v in pts)
                vals = [v for _, v in sorted(pts)]
                mono = all(x >= y for x, y in zip(vals, vals[1:]))
        row = {"e_lo": str(e_lo), "e_hi": str(e_hi), "width": str(e_hi - e_lo), "N": r["N"], "kind": r["kind"],
               "certified": c["certified"], "bound": c["w_atom_float"], "bound_exact": c["w_atom"],
               "alpha": r["alpha_float"], "beta": r["beta_float"], "cpu_s": r["cpu_seconds"]["total"],
               "cells_x_slabs": c.get("cells_checked"), "sup_truth": sup, "truth_decreasing_on_grid": mono,
               "excess_pct": (100 * (c["w_atom_float"] / sup - 1)) if sup else None}
        if r["kind"] == "taboo":
            row["C_T_bound"] = float(F(c["w_max"]))
            # the Lambda-grid sup does not apply to the taboo kernel; compare with tau_a(e_lo) (a lower bound of sup)
            row["sup_truth"] = None
            row["excess_pct"] = None
            tb = (T or {}).get(str(e_lo), {}).get("best", {})
            if tb.get("tau_a"):
                row["tau_truth_e_lo"] = tb["tau_a"]["best"]
                row["excess_vs_tau_e_lo_pct"] = 100 * (c["w_atom_float"] / tb["tau_a"]["best"] - 1)
            if tb.get("C_T"):
                row["C_T_truth_e_lo"] = tb["C_T"]["best"]
                row["C_T_excess_vs_e_lo_pct"] = 100 * (row["C_T_bound"] / tb["C_T"]["best"] - 1)
        # robust (adversarial drift) ARL on the lattice drift grid, same block, same mesh if available
        rob = _load(f"robust_{str(e_lo).replace('/', '_')}_{str(e_hi - e_lo).replace('/', '_')}_N*.json")
        rN = {v["N"]: v for v in rob.values()}
        rr = rN.get(r["N"]) or (rN[max(rN)] if rN else None)
        if rr and r["kind"] == "whole":
            row["robust_Lambda_star"] = rr["W_atom"]
            row["robust_N"] = rr["N"]
            row["robust_same_mesh_Lambdas"] = rr["Lambdas"]
            lam_lo_same = max(rr["Lambdas"])
            row["intrinsic_floor_pct"] = 100 * (rr["W_atom"] / lam_lo_same - 1)   # same-mesh ratio
            row["overhead_vs_robust_pct"] = 100 * (c["w_atom_float"] / rr["W_atom"] - 1)
        rows.append(row)
    rows.sort(key=lambda x: (F(x["e_lo"]), x["kind"], F(x["width"]), x["N"]))
    return rows


def md(rows, cols):
    head = "| " + " | ".join(cols) + " |\n|" + "---|" * len(cols) + "\n"
    body = ""
    for r in rows:
        cells = []
        for c in cols:
            v = r.get(c)
            cells.append(f"{v:.6g}" if isinstance(v, float) else str(v))
        body += "| " + " | ".join(cells) + " |\n"
    return head + body


def main():
    T = truth_table()
    P = point_rows(T)
    B = block_rows(T)
    C = _load("controls_*.json")
    import c2b_certify as CE
    L = []
    for e in sorted({r["e"] for r in P}, key=F):
        for kind in ("whole", "taboo"):
            rr = sorted([r for r in P if r["e"] == e and r["kind"] == kind and r["family"] == "P1"],
                        key=lambda r: r["N"])
            if rr:
                rungs = [(r["N"], F(r["bound_exact"]) if r["certified"] else None, r["cpu_s"]) for r in rr]
                stop, why, best = CE.ladder_decision(rungs)
                L.append({"e": e, "kind": kind, "rungs_run": [r["N"] for r in rr], "stop_after_N": stop,
                          "reason": why, "best": float(best) if best else None})
    out = {"schema": "C2B_VALIDATION/1", "stream": "C2b", "label": "NON-TARGET VALIDATION ONLY",
           "truth": {e: d["best"] for e, d in T.items()}, "pointwise": P, "blocks": B, "controls": C,
           "ladder_decisions_post_hoc": L,
           "fdcheck_r1": json.loads((RES / "fdcheck_r1.json").read_text()) if (RES / "fdcheck_r1.json").exists() else None,
           "notes": [
               "controls_*.json field C4_hessian_fd used a sampler over the (s,y) rectangle, a superset of the domain on "
               "which the Hessian bounds are claimed (the cell); its 3 exceedances at e=1/2,N=20 are out-of-domain. "
               "SUPERSEDED by fdcheck_r1 (in-cell sampler). The certificate code is unchanged.",
               "NOT RUN: N=80 rungs requested by the post-hoc ladder rule for e=0 taboo, e=1/4 whole/taboo, e=1 taboo "
               "(not in the declared validation set; projected cost near/above the 20-min cap).",
               "F0 comparator: rows with slope at the edge of the declared grid are grid-limited; taboo F0 at e<=1/2 "
               "found no feasible parameters (NOT CERTIFIED).",
               "Theorem M: the logical transfer of |e|<=1 bounds to larger |e| exists and is not used anywhere here.",
           ]}
    p = CM.VALIDATION_DIR / "C2B_VALIDATION.json"
    p.write_text(json.dumps(out, indent=1, sort_keys=True, default=str) + "\n")
    print(md(P, ["e", "kind", "family", "N", "certified", "bound", "truth", "truth_unc", "tightness_pct", "alpha",
                 "beta", "bumps", "cpu_s"]))
    tb = [r for r in P if r["kind"] == "taboo"]
    print(md(tb, ["e", "N", "C_T_bound", "C_T_truth", "C_T_tightness_pct"]))
    print(md(B, ["e_lo", "width", "N", "kind", "certified", "bound", "sup_truth", "excess_pct",
                 "robust_Lambda_star", "robust_N", "intrinsic_floor_pct", "overhead_vs_robust_pct",
                 "truth_decreasing_on_grid", "alpha", "beta", "cpu_s"]))
    print(md(L, ["e", "kind", "rungs_run", "stop_after_N", "reason", "best"]))
    print(md([b for b in B if b["kind"] == "taboo"], ["e_lo", "width", "N", "bound", "tau_truth_e_lo",
             "excess_vs_tau_e_lo_pct", "C_T_bound", "C_T_truth_e_lo", "C_T_excess_vs_e_lo_pct", "cpu_s"]))
    print("wrote", p)


if __name__ == "__main__":
    main()
