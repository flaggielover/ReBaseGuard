"""Turns results/consequences.json into the reported tables and the boundary
verdict.  Emits results/boundary_verdict.json and STATISTICAL_CONSEQUENCES.md.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from rebaseguard_p7.config import DETECTORS, M_GRID, RESULTS            # noqa: E402

CAMPAIGN = Path(__file__).resolve().parents[1]
LADDER = (0.25, 0.5, 0.8, 1.0, 1.25, 1.5, 2.0, 4.0)
METRICS = ("arl", "ref_mse", "fap100", "e_acf1", "R_delta_1")


def metric_value(c: dict, name: str) -> float:
    if name == "fap100":
        return c["fap"]["100"]["est"]
    if name == "R_delta_1":
        return c["delay"]["1.0"]["R_delta"]
    return c[name]


def boundary_verdict(cells: list[dict]) -> dict:
    """Pre-committed criterion, EXPERIMENT_DESIGN.md section 8."""
    fams, per_metric = {}, {m: 0 for m in METRICS}
    for d in DETECTORS:
        for m in M_GRID:
            rung = []
            for f in LADDER:
                match = [c for c in cells
                         if c["detector"] == d and c["m"] == m
                         and abs(c["rho_over_rhoc"] - f) < 1e-6]
                if match:
                    rung.append((f, match[0]))
            info = {}
            for name in METRICS:
                xs = np.log(np.array([f for f, _ in rung]))
                ys = np.array([metric_value(c, name) for _, c in rung])
                # relative rate for positive metrics, absolute for the ACF
                if name == "e_acf1":
                    rates = np.abs(np.diff(ys) / np.diff(xs))
                else:
                    rates = np.abs(np.diff(np.log(np.abs(ys))) / np.diff(xs))
                labels = [f"{rung[i][0]}-{rung[i+1][0]}" for i in range(len(rung) - 1)]
                bi = [i for i, lab in enumerate(labels)
                      if lab in ("0.8-1.0", "1.0-1.25")]
                bmax = float(rates[bi].max())
                others = np.delete(rates, bi)
                peaks = bool(bmax > others.max())
                info[name] = {
                    "boundary_rate": bmax,
                    "max_rate_elsewhere": float(others.max()),
                    "argmax_bracket": labels[int(np.argmax(rates))],
                    "peaks_at_boundary": peaks,
                    "rates": {lab: float(r) for lab, r in zip(labels, rates)},
                }
                per_metric[name] += int(peaks)
            fams[f"{d}_m{m}"] = info
    n_fam = len(fams)
    any_metric = any(v >= n_fam / 2 for v in per_metric.values())
    return {
        "criterion": ("the rate across the bracket containing rho/rho_c = 1 must "
                      "be the maximum over all brackets, in at least half of the "
                      "eight (detector, m) families, for at least one "
                      "pre-specified metric"),
        "ladder": list(LADDER), "metrics": list(METRICS),
        "n_families": n_fam,
        "families_peaking_at_boundary_per_metric": per_metric,
        "criterion_met": bool(any_metric),
        "verdict": ("OBSERVABLE_BOUNDARY_CONSEQUENCE" if any_metric else
                    "LOCAL-MATHEMATICAL, NOT OPERATIONAL"),
        "families": fams,
    }


def fmt(x, n=2):
    return "n/a" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.{n}f}"


def main() -> None:
    res = json.loads((RESULTS / "consequences.json").read_text())
    cells = res["cells"]
    bv = boundary_verdict(cells)
    (RESULTS / "boundary_verdict.json").write_text(json.dumps(bv, indent=1))

    idx = {(c["detector"], c["m"], round(c["rho"], 10)): c for c in cells}
    L = []
    A0 = {d: res["curve_summary"][d]["A0"] for d in DETECTORS}

    L += ["# P7 statistical consequences", "",
          "Generated by `experiments/make_report.py` from `results/consequences.json`.",
          "Verdict labels are the pre-committed ones of `EXPERIMENT_DESIGN.md` §7.", ""]

    L += ["## 1. Headline: what re-baselining costs, and what reuse adds to it", "",
          "`nominal` is `A(0)`, the calibrated in-control ARL of a reference that is "
          "never updated. `fresh` is `rho = 0` at the same `m`. Reuse-attributable "
          "effects are always quoted against `fresh`.", "",
          "| det | m | nominal A(0) | fresh (rho=0) | vs nominal | full reuse (rho=1) | vs nominal | vs fresh | verdict (vs fresh) |",
          "|---|---|---|---|---|---|---|---|---|"]
    for d in DETECTORS:
        for m in M_GRID:
            f0, f1 = idx[(d, m, 0.0)], idx[(d, m, 1.0)]
            L.append(
                f"| {d} | {m} | {A0[d]:.1f} | {f0['arl']:.1f} ± {f0['arl_se']:.1f} | "
                f"{100*f0['rel_vs_nominal']:+.1f}% | {f1['arl']:.1f} ± {f1['arl_se']:.1f} | "
                f"{100*f1['rel_vs_nominal']:+.1f}% | "
                f"{100*f1['rel_vs_fresh']:+.1f}% "
                f"[{100*f1['rel_vs_fresh_ci'][0]:+.1f}, {100*f1['rel_vs_fresh_ci'][1]:+.1f}] | "
                f"{f1['rel_vs_fresh_verdict']} |")
    L.append("")

    L += ["## 2. In-control ARL across the reuse ladder", "",
          "| det | m | rho/rho_c | rho | ARL_0 | 95% boot CI | vs fresh | verdict |",
          "|---|---|---|---|---|---|---|---|"]
    for d in DETECTORS:
        for m in M_GRID:
            rows = sorted((c for c in cells if c["detector"] == d and c["m"] == m),
                          key=lambda c: c["rho"])
            for c in rows:
                L.append(f"| {d} | {m} | {c['rho_over_rhoc']:.2f} | {c['rho']:.4f} | "
                         f"{c['arl']:.1f} | [{c['arl_boot_ci'][0]:.1f}, {c['arl_boot_ci'][1]:.1f}] | "
                         f"{100*c['rel_vs_fresh']:+.1f}% | {c['rel_vs_fresh_verdict']} |")
    L.append("")

    L += ["## 3. Reference dispersion, false alarms and the effective multiplier", "",
          "`disp/r_lin` is the empirical post-burn-in reference RMS divided by a "
          "grid-defined 10%-tolerance linearisation radius. Both have reference-error "
          "units, so the ratio is dimensionless; `r_lin` is a diagnostic, not a "
          "proved radius of validity.", "",
          "| det | m | rho/rho_c | MSE(e) | disp/r_lin | FAR/1000 | FAP(100) | ACF1 meas | rho(1-Gamma_eff) | P3 lambda |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for d in DETECTORS:
        for m in M_GRID:
            rows = sorted((c for c in cells if c["detector"] == d and c["m"] == m),
                          key=lambda c: c["rho"])
            for c in rows:
                L.append(
                    f"| {d} | {m} | {c['rho_over_rhoc']:.2f} | {c['ref_mse']:.4f} | "
                    f"{c['dispersion_over_lin_radius']:.1f} | {c['far_per_1000']:.2f} | "
                    f"{c['fap']['100']['est']:.4f} | {c['e_acf1']:+.4f} | "
                    f"{c['acf1_predicted_from_gamma_eff']:+.4f} | "
                    f"{c['acf1_predicted_from_p3_lambda']:+.3f} |")
    L.append("")

    L += ["## 4. Detection delay (identity route, validated in "
          "`results/delay_validation.json`)", "",
          "`blind spot` is `P(|e - Delta| < 0.2)`: the pre-shift dispersed reference "
          "happens to lie near the post-change mean, so the first shifted cycle looks "
          "in control. Changed observations do not construct that entering reference.", "",
          "| det | m | rho/rho_c | delay D=1.0 | nominal | vs nominal | R_Delta | blind spot | P(cycle mean > A(0)/2) |",
          "|---|---|---|---|---|---|---|---|---|"]
    for d in DETECTORS:
        for m in M_GRID:
            for c in sorted((c for c in cells if c["detector"] == d and c["m"] == m),
                            key=lambda c: c["rho"]):
                b = c["delay"]["1.0"]
                L.append(f"| {d} | {m} | {c['rho_over_rhoc']:.2f} | {b['delay_chain']:.2f} | "
                         f"{b['delay_nominal']:.2f} | {100*b['relative']:+.1f}% | "
                         f"{b['R_delta']:.3f} | {b['p_blind_spot']:.4f} | "
                         f"{b['p_delay_exceeds_half_nominal_arl']:.4f} |")
    L.append("")

    dv = json.loads((RESULTS / "delay_validation.json").read_text())["cells"]
    L += ["### 4b. The delay inflation is a heavy right tail, not a uniform slowdown", "",
          "Direct shifted-chain simulation (`n_rep = 40,000`), shift applied at a "
          "re-baselining instant. The **median** delay is at or below nominal: most "
          "cycles still detect quickly, and a dispersed reference often makes the "
          "shift look larger. The mean is inflated by a tail of cycles in which the "
          "pre-shift reference happens to lie near the post-change mean and the shift is "
          "invisible. Reporting only the mean would misdescribe the failure mode.", "",
          "| det | m | rho | Delta | nominal | mean | median | q75 | q95 | P(delay>100) | identity gap |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in dv:
        L.append(f"| {r['detector']} | {r['m']} | {r['rho']:g} | {r['shift']:g} | "
                 f"{r['nominal_delay']:.2f} | {r['direct_mean']:.1f} ± {r['direct_se']:.1f} | "
                 f"{r['direct_median']:.0f} | {r['direct_q75']:.0f} | {r['direct_q95']:.0f} | "
                 f"{r['direct_p_gt_100']:.4f} | {100*r['relative_gap']:+.1f}% (z={r['z']:+.2f}) |")
    L.append("")

    L += ["## 5. Finite-cycle decay of the calibration promise", "",
          "Every chain starts at `e_0 = 0` exactly (the frozen safe reference). "
          "`ARL_j` is the mean length of cycle `j`.", "",
          "| det | m | rho | ARL_1 | ARL_2 | ARL_3 | ARL_5 | ARL_10 | ARL_20 | ARL_50 | cycles to lose 25% |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    for d in DETECTORS:
        for m in M_GRID:
            for rho in (0.0, 1.0):
                c = idx[(d, m, rho)]
                ca = c["cycle_arl"]
                loss = next((j + 1 for j, v in enumerate(ca) if v < 0.75 * ca[0]), None)
                L.append(f"| {d} | {m} | {rho:.2f} | " +
                         " | ".join(f"{ca[j-1]:.1f}" for j in (1, 2, 3, 5, 10, 20, 50)) +
                         f" | {loss if loss else '>50'} |")
    L.append("")

    L += ["## 6. Pre-committed boundary criterion", "",
          f"**Verdict: `{bv['verdict']}`** (criterion met: {bv['criterion_met']}). "
          "This is the fixed point-estimate/grid criterion, not proof that no other "
          "operational signature can exist.", "",
          "Families (out of 8) in which the rate peaks in the bracket containing "
          "`rho/rho_c = 1`:", "",
          "| metric | families peaking at the boundary |", "|---|---|"]
    for k, v in bv["families_peaking_at_boundary_per_metric"].items():
        L.append(f"| `{k}` | {v} / {bv['n_families']} |")
    L += ["", "Where the rate actually peaks, per family and metric:", "",
          "| family | " + " | ".join(f"`{k}`" for k in METRICS) + " |",
          "|---|" + "---|" * len(METRICS)]
    for fam, info in bv["families"].items():
        L.append(f"| {fam} | " + " | ".join(info[k]["argmax_bracket"] for k in METRICS) + " |")
    L.append("")

    L += ["## 7. Conditional ARL-deficit plug-in diagnostic (P7-D)", "",
          "The algebra assumes stationarity, a global sign condition for `h`, a finite "
          "fourth moment, and monotonicity of `A`. The table substitutes Monte Carlo "
          "point estimates without simultaneous uncertainty propagation; these are not "
          "certified bounds.", "",
          "| det | m | rho | rho*beta_r | best r | plug-in P(|e|>r) lower | plug-in ARL upper | plug-in deficit | measured ARL |",
          "|---|---|---|---|---|---|---|---|---|"]
    for d in DETECTORS:
        for m in M_GRID:
            for c in sorted((c for c in cells if c["detector"] == d and c["m"] == m),
                            key=lambda c: c["rho"]):
                rb = c["repulsion_bound"]
                if rb is None or rb["plug_in_relative_deficit"] < 1e-4:
                    continue
                L.append(f"| {d} | {m} | {c['rho']:.3f} | {rb['rho_beta_r']:.2f} | {rb['r']} | "
                         f"{rb['plug_in_p_tail_lower']:.4f} | {rb['plug_in_arl_upper_bound']:.1f} | "
                         f"{100*rb['plug_in_relative_deficit']:.1f}% | {c['arl']:.1f} |")
    L.append("")

    L += ["## 8. Response-curve summary", "",
          "| det | A(0) | A''(0) | GammaTilde re-measured (m=1,2,3,5) | P3 GammaTilde | r_lin | sup abs h |",
          "|---|---|---|---|---|---|---|"]
    for d in DETECTORS:
        s = res["curve_summary"][d]
        L.append(f"| {d} | {s['A0']:.2f} ± {s['A0_se']:.2f} | {s['arl_second_derivative_at_0']:.0f} | " +
                 ", ".join(f"{s['gamma_tilde_remeasured'][str(m)]:.3f}" for m in M_GRID) + " | " +
                 ", ".join(f"{s['gamma_tilde_p3'][str(m)]:.3f}" for m in M_GRID) + " | " +
                 ", ".join(f"{s['linearisation_radius'][str(m)]:.3f}" for m in M_GRID) + " | " +
                 ", ".join(f"{s['selection_bias_sup'][str(m)]:.3f}" for m in M_GRID) + " |")
    (CAMPAIGN / "STATISTICAL_CONSEQUENCES.md").write_text("\n".join(L) + "\n")
    print("boundary verdict:", bv["verdict"])
    print("wrote STATISTICAL_CONSEQUENCES.md and results/boundary_verdict.json")


if __name__ == "__main__":
    main()
