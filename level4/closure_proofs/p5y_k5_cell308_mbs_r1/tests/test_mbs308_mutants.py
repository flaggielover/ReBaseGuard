def repin(code: Path) -> None:
    drv = code / "mbs308_driver.py"
    s = drv.read_text()
    for name in HELPERS:
        h = hashlib.sha256((code / name).read_bytes()).hexdigest()
        s, n = re.subn(r'("%s": )"[0-9a-f]{64}"' % re.escape(name), r'\1"%s"' % h, s)
        assert n == 1, name
    drv.write_text(s)


